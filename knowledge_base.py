    if not user_input or not user_input.strip():
        return "Please ask a question or type a subject keyword!"

    # Clean and normalize raw user input
    clean_input = user_input.strip().lower()
    normalized_input = re.sub(r'[^\w\s]', '', clean_input)

    # Strategy 1: Exact Key Match
    if clean_input in KNOWLEDGE_BASE:
        return KNOWLEDGE_BASE[clean_input]

    # Strategy 2: Normalized Key Match (ignoring punctuation like '?' or '.')
    for key, answer in KNOWLEDGE_BASE.items():
        normalized_key = re.sub(r'[^\w\s]', '', key)
        if normalized_input == normalized_key:
            return answer

